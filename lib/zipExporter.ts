import JSZip from 'jszip';
import { PlatformExport, StudioConfig } from './types';

export async function exportPlatformZip(
  platformExport: PlatformExport,
  config: StudioConfig
): Promise<Blob> {
  const zip = new JSZip();

  // Add individual generated code files
  for (const file of platformExport.files) {
    zip.file(file.path, file.content);
  }

  // Add raw logo SVG
  zip.file('assets/logo.svg', config.logoSvg);

  // Add comprehensive README
  const readmeContent = `# Native Splash Screen Package: ${platformExport.platformName}
Generated by **NativeSplash Studio** for ${config.appName}

## Configuration
- Template: ${config.templateId}
- Duration: ${config.durationMs}ms
- Background: ${config.backgroundColor}
- Accent Color: ${config.accentColor}

## Integration Steps
${platformExport.setupGuide.map((step) => `${step}`).join('\n')}

---
Generated by NativeSplash Studio. 100% Native OS Execution.
`;
  zip.file('README.md', readmeContent);

  return await zip.generateAsync({ type: 'blob' });
}

export function triggerBlobDownload(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
